#!/usr/bin/env bash
set -euo pipefail

# ------------------------------------------------------------------------------
# HosteDay Flutter SDK - Example Sanitization Script
# ------------------------------------------------------------------------------
# Backs up live credentials to .local_secrets/ and replaces all project-specific
# API keys, tokens, and endpoints with safe template dummy values for publishing.
# ------------------------------------------------------------------------------

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SECRETS_DIR="$ROOT_DIR/.local_secrets"

echo "🔒 [HosteDay] Starting sanitization of example credentials..."

# 1. Ensure backup directory exists
mkdir -p "$SECRETS_DIR/lib"
mkdir -p "$SECRETS_DIR/example/lib"
mkdir -p "$SECRETS_DIR/example/web"
mkdir -p "$SECRETS_DIR/example/android/app"
mkdir -p "$SECRETS_DIR/example/android"
mkdir -p "$SECRETS_DIR/example/ios/Runner"

# 2. Backup real files if they exist and are not already templates
backup_if_real() {
  local src="$1"
  local dst="$2"
  if [[ -f "$src" ]]; then
    # Only overwrite backup if source has non-dummy real credentials
    if ! grep -q "example-app\|example_app\|YOUR_HOSTE_DAY_TOKEN_HERE\|AIzaSy_YOUR_DUMMY\|example-firebase-project" "$src" 2>/dev/null; then
      cp "$src" "$dst"
      echo "  ✓ Backed up $(basename "$src") to $dst"
    fi
  fi
}

backup_if_real "$ROOT_DIR/lib/hosteday_config.dart" "$SECRETS_DIR/lib/hosteday_config.dart"
backup_if_real "$ROOT_DIR/example/lib/hosteday_config.dart" "$SECRETS_DIR/example/lib/hosteday_config.dart"
backup_if_real "$ROOT_DIR/example/web/firebase-config.json" "$SECRETS_DIR/example/web/firebase-config.json"
backup_if_real "$ROOT_DIR/example/web/firebase-messaging-sw.js" "$SECRETS_DIR/example/web/firebase-messaging-sw.js"
backup_if_real "$ROOT_DIR/example/android/app/google-services.json" "$SECRETS_DIR/example/android/app/google-services.json"
backup_if_real "$ROOT_DIR/example/android/google-services.json" "$SECRETS_DIR/example/android/google-services.json"
backup_if_real "$ROOT_DIR/example/ios/Runner/GoogleService-Info.plist" "$SECRETS_DIR/example/ios/Runner/GoogleService-Info.plist"

# 3. Write dummy hosteday_config.dart template
cat << 'EOF' > "$ROOT_DIR/example/lib/hosteday_config.dart"
// Generated by HosteDay Flutter CLI (Template Placeholder)
class HosteDayConfig {
  // App Identifiers
  static const String projectName = 'example_app';
  static const String appPackageName = 'com.example.app';
  static const String bundleIdentifier = 'com.example.app';
  static const String appName = 'example_app';
  static const String slug = 'example-app';

  // Base API URL & Credentials
  static const String baseUrl = 'https://api.example.com';
  static const String baseApiUrl = 'https://api.example.com';
  static const String environmentId = '00000000-0000-0000-0000-000000000000';
  static const String token = 'YOUR_HOSTE_DAY_TOKEN_HERE';

  // Features
  static const bool pushNotifications = true;
  static const bool pushNotificationsEnabled = true;
  static const bool realtimeWebsocketsEnabled = true;

  // Firebase Configuration
  static const String? firebaseProjectId = 'example-firebase-project';

  // WebSockets (Reverb) Configuration
  static const String websocketUrl = 'wss://ws.example.com';
  static const String wsHost = 'ws.example.com';
  static const int wsPort = 443;
  static const String wsScheme = 'https';
  static const String wsKey = 'YOUR_WS_APP_KEY';
  static const String wsChannel =
      'environment.00000000-0000-0000-0000-000000000000';

  // Core API Endpoints
  static const String deviceRegisterEndpoint =
      '/api/notifications/devices/register';
  static const String deviceUnregisterEndpoint =
      '/api/notifications/devices/unregister';
  static const String loginEndpoint = '/api/login';
  static const String registerEndpoint = '/api/register';
  static const String userEndpoint = '/api/user';
}
EOF

# Sync root lib/hosteday_config.dart template
cp "$ROOT_DIR/example/lib/hosteday_config.dart" "$ROOT_DIR/lib/hosteday_config.dart"
echo "  ✓ Sanitized lib/hosteday_config.dart & example/lib/hosteday_config.dart"

# 4. Write dummy web/firebase-config.json template
cat << 'EOF' > "$ROOT_DIR/example/web/firebase-config.json"
{
  "apiKey": "AIzaSy_YOUR_DUMMY_WEB_API_KEY_HERE",
  "authDomain": "example-app.firebaseapp.com",
  "projectId": "example-firebase-project",
  "storageBucket": "example-firebase-project.firebasestorage.app",
  "messagingSenderId": "000000000000",
  "appId": "1:000000000000:web:0000000000000000000000"
}
EOF
echo "  ✓ Sanitized example/web/firebase-config.json"

# Sanitize example/web/firebase-messaging-sw.js
if [[ -f "$ROOT_DIR/example/web/firebase-messaging-sw.js" ]]; then
  sed -i 's/apiKey: "AIzaSy[^"]*"/apiKey: "AIzaSy_YOUR_DUMMY_WEB_API_KEY_HERE"/' "$ROOT_DIR/example/web/firebase-messaging-sw.js"
  sed -i 's/authDomain: "[^"]*"/authDomain: "example-app.firebaseapp.com"/' "$ROOT_DIR/example/web/firebase-messaging-sw.js"
  sed -i 's/projectId: "[^"]*"/projectId: "example-firebase-project"/' "$ROOT_DIR/example/web/firebase-messaging-sw.js"
  sed -i 's/storageBucket: "[^"]*"/storageBucket: "example-firebase-project.firebasestorage.app"/' "$ROOT_DIR/example/web/firebase-messaging-sw.js"
  sed -i 's/messagingSenderId: "[^"]*"/messagingSenderId: "000000000000"/' "$ROOT_DIR/example/web/firebase-messaging-sw.js"
  sed -i 's/appId: "[^"]*"/appId: "1:000000000000:web:0000000000000000000000"/' "$ROOT_DIR/example/web/firebase-messaging-sw.js"
  echo "  ✓ Sanitized example/web/firebase-messaging-sw.js"
fi

# 5. Write dummy android google-services.json template
cat << 'EOF' > "$ROOT_DIR/example/android/app/google-services.json"
{
  "project_info": {
    "project_number": "000000000000",
    "project_id": "example-firebase-project",
    "storage_bucket": "example-firebase-project.firebasestorage.app"
  },
  "client": [
    {
      "client_info": {
        "mobilesdk_app_id": "1:000000000000:android:0000000000000000000000",
        "android_client_info": {
          "package_name": "com.example.app"
        }
      },
      "oauth_client": [],
      "api_key": [
        {
          "current_key": "AIzaSy_YOUR_DUMMY_ANDROID_API_KEY_HERE"
        }
      ],
      "services": {
        "appinvite_service": {
          "other_platform_oauth_client": []
        }
      }
    }
  ],
  "configuration_version": "1"
}
EOF
cp "$ROOT_DIR/example/android/app/google-services.json" "$ROOT_DIR/example/android/google-services.json"
echo "  ✓ Sanitized example/android/app/google-services.json"

# 6. Write dummy ios GoogleService-Info.plist template
cat << 'EOF' > "$ROOT_DIR/example/ios/Runner/GoogleService-Info.plist"
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>API_KEY</key>
	<string>AIzaSy_YOUR_DUMMY_IOS_API_KEY_HERE</string>
	<key>GCM_SENDER_ID</key>
	<string>000000000000</string>
	<key>PLIST_VERSION</key>
	<string>1</string>
	<key>BUNDLE_ID</key>
	<string>com.example.app</string>
	<key>PROJECT_ID</key>
	<string>example-firebase-project</string>
	<key>STORAGE_BUCKET</key>
	<string>example-firebase-project.firebasestorage.app</string>
	<key>IS_ADS_ENABLED</key>
	<false></false>
	<key>IS_ANALYTICS_ENABLED</key>
	<false></false>
	<key>GOOGLE_APP_ID</key>
	<string>1:000000000000:ios:0000000000000000000000</string>
</dict>
</plist>
EOF
echo "  ✓ Sanitized example/ios/Runner/GoogleService-Info.plist"

echo "✨ [HosteDay] Sanitization complete! All sensitive credentials are clean and safely backed up in .local_secrets/"
